#!/usr/bin/env python3
"""Generate src/PRTSCN/Theme.g.cs from design/tokens.json. Run after any token change."""
import json, pathlib, re
root = pathlib.Path(__file__).resolve().parent.parent
t = json.loads((root / "design/tokens.json").read_text())
def pascal(k): return "".join(p.capitalize() for p in re.split(r"[-_]", k))
def col(h): return f"Color.FromArgb(0x{h[1:3]}, 0x{h[3:5]}, 0x{h[5:7]})"
L = ["// <auto-generated> by tools/gen_theme.py from design/tokens.json. Do not edit.</auto-generated>",
     "using System.Drawing;", "", "namespace PRTSCN;", "", "internal static partial class Theme", "{"]
for k, v in t["color"].items(): L.append(f"    public static readonly Color {pascal(k)} = {col(v)};")
for k, v in t["alpha"].items(): L.append(f"    public const int Alpha{pascal(k)} = {round(v*255)};")
L.append("    public static readonly Color[] Ink = { " + ", ".join(col(c) for c in t["ink"]) + " };")
for k, v in t["size"].items(): L.append(f"    public const int Size{pascal(k)} = {v};")
for k, v in t["radius"].items(): L.append(f"    public const int Radius{pascal(k)} = {v};")
for k, v in t["stroke"].items(): L.append(f"    public const float Stroke{pascal(k)} = {v}f;")
for k, v in t["type"].items(): L.append(f"    public const float Type{pascal(k)} = {v['size']}f; public const bool Type{pascal(k)}Bold = {str(v['weight']>=600).lower()};")
fam = t["font"]["sans"].split(",")
L.append("    public static readonly string[] FontFamilies = { " + ", ".join('"%s"' % f.strip() for f in fam if f.strip() != "sans-serif") + " };")
L.append("}")
(root / "src/PRTSCN/Theme.g.cs").write_text("\n".join(L) + "\n")
print("wrote src/PRTSCN/Theme.g.cs")
